static inline bool get_box_drawing_glyph(uint32_t codepoint, uint8_t glyph[8]) {
    memset(glyph, 0, 8);
    
    if (codepoint == 0x2500) { 
        glyph[3] = 0xFF; glyph[4] = 0xFF; 
        return true;
    }
    if (codepoint == 0x2502) { 
        for (int r = 0; r < 8; r++) glyph[r] = 0x18; 
        return true;
    }
    if (codepoint == 0x250C) {
        glyph[3] = 0x1F; glyph[4] = 0x1F; 
        glyph[5] = glyph[6] = glyph[7] = 0x18; 
        return true;
    }
    if (codepoint == 0x2510) { 
        glyph[3] = 0xF8; glyph[4] = 0xF8; 
        glyph[5] = glyph[6] = glyph[7] = 0x18; 
        return true;
    }
    if (codepoint == 0x2514) { 
        glyph[3] = 0x1F; glyph[4] = 0x1F; 
        glyph[0] = glyph[1] = glyph[2] = 0x18; 
        return true;
    }
    if (codepoint == 0x2518) { 
        glyph[3] = 0xF8; glyph[4] = 0xF8; 
        glyph[0] = glyph[1] = glyph[2] = 0x18; 
        return true;
    }
    if (codepoint == 0x251C) { 
        for (int r = 0; r < 8; r++) glyph[r] = 0x18;
        glyph[3] |= 0x0F; glyph[4] |= 0x0F; 
        return true;
    }
    if (codepoint == 0x2524) { 
        for (int r = 0; r < 8; r++) glyph[r] = 0x18; 
        glyph[3] |= 0xF0; glyph[4] |= 0xF0; 
        return true;
    }
    if (codepoint == 0x252C) { 
        glyph[3] = 0xFF; glyph[4] = 0xFF; 
        glyph[5] = glyph[6] = glyph[7] = 0x18; 
        return true;
    }
    if (codepoint == 0x2534) { 
        glyph[3] = 0xFF; glyph[4] = 0xFF; 
        glyph[0] = glyph[1] = glyph[2] = 0x18; 
        return true;
    }
    if (codepoint == 0x253C) { 
        for (int r = 0; r < 8; r++) glyph[r] = 0x18;
        glyph[3] = 0xFF; glyph[4] = 0xFF; 
        return true;
    }
    
    if (codepoint == 0x2550) {
        glyph[2] = 0xFF; glyph[5] = 0xFF;
        return true;
    }
    if (codepoint == 0x2551) {
        for (int r = 0; r < 8; r++) glyph[r] = 0x24;
        return true;
    }
    if (codepoint == 0x2554) { 
        glyph[2] = 0x3F; glyph[5] = 0x0F;
        glyph[3] = glyph[4] = 0x24;
        glyph[6] = glyph[7] = 0x24;
        return true;
    }
    if (codepoint == 0x2557) { 
        glyph[2] = 0xFC; glyph[5] = 0xF0;
        glyph[3] = glyph[4] = 0x24;
        glyph[6] = glyph[7] = 0x24;
        return true;
    }
    if (codepoint == 0x255A) {
        glyph[5] = 0x3F; glyph[2] = 0x0F;
        glyph[3] = glyph[4] = 0x24;
        glyph[0] = glyph[1] = 0x24;
        return true;
    }
    if (codepoint == 0x255D) { 
        glyph[5] = 0xFC; glyph[2] = 0xF0;
        glyph[3] = glyph[4] = 0x24;
        glyph[0] = glyph[1] = 0x24;
        return true;
    }
    if (codepoint == 0x2560) { 
        for (int r = 0; r < 8; r++) glyph[r] = 0x24;
        glyph[2] |= 0x3F; glyph[5] |= 0x3F;
        return true;
    }
    if (codepoint == 0x2563) {
        for (int r = 0; r < 8; r++) glyph[r] = 0x24;
        glyph[2] |= 0xFC; glyph[5] |= 0xFC;
        return true;
    }
    if (codepoint == 0x2566) { 
        glyph[2] = 0xFF; glyph[5] = 0xFF;
        glyph[3] = glyph[4] = 0x24;
        glyph[6] = glyph[7] = 0x24;
        return true;
    }
    if (codepoint == 0x2569) { 
        glyph[2] = 0xFF; glyph[5] = 0xFF;
        glyph[3] = glyph[4] = 0x24;
        glyph[0] = glyph[1] = 0x24;
        return true;
    }
    if (codepoint == 0x256C) { 
        for (int r = 0; r < 8; r++) glyph[r] = 0x24;
        glyph[2] = 0xFF; glyph[5] = 0xFF;
        return true;
    }

    if (codepoint == 0x2588) { 
        for (int r = 0; r < 8; r++) glyph[r] = 0xFF;
        return true;
    }
    
    return false;
}

